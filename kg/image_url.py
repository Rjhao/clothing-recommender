"""Shared image URL resolver.

Provides a single resolve_image() used by both the clothing service and the
recommendation engine so every endpoint returns a displayable image:

  - real image_url values are kept as-is, except wikimedia.org URLs which are
    unreachable from some networks (e.g. CN);
  - missing / wikimedia URLs fall back to a real, category-matched Pexels stock
    photo (see data/pexels_images.json, generated by data.crawl_pexels_images);
  - if the Pexels JSON is unavailable, falls back further to loremflickr.

If your network can reach wikimedia, drop the wikimedia condition to use originals.
"""
import json
import os
from typing import Optional


_PEXELS_JSON = os.path.join(
    os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
    "data",
    "pexels_images.json",
)

try:
    with open(_PEXELS_JSON, "r", encoding="utf-8") as _f:
        _PEXELS_IMAGES = json.load(_f)
except (FileNotFoundError, json.JSONDecodeError):
    _PEXELS_IMAGES = {}


# Fallback when the Pexels JSON is missing: loremflickr keyword per category.
_CATEGORY_IMAGE_KEYWORD = {
    "top": "tshirt",
    "bottom": "jeans",
    "dress": "dress",
    "outerwear": "jacket",
    "shoes": "sneakers",
    "accessories": "handbag",
}


def resolve_image(item: dict) -> Optional[str]:
    """Return a displayable image URL for a clothing item dict.

    Reads item['image_url'] / ['Image_url'] / ['category'] / ['id']|['product_id']
    tolerantly, so it works for any of the schema variants in the codebase.
    """
    url = item.get("image_url") or item.get("Image_url")
    if url and "wikimedia.org" not in url:
        return url
    cat = (item.get("category") or "").lower()
    raw = item.get("id")
    if raw is None:
        raw = item.get("product_id", 0)
    try:
        cid = int(raw)
    except (TypeError, ValueError):
        cid = 0
    # Prefer a real Pexels photo for this category, pinned per-product.
    urls = _PEXELS_IMAGES.get(cat)
    if urls:
        return urls[cid % len(urls)]
    # Final fallback: loremflickr (reachable, real Flickr photo by keyword).
    kw = _CATEGORY_IMAGE_KEYWORD.get(cat, "fashion")
    return f"https://loremflickr.com/400/500/{kw}?lock={cid}"
